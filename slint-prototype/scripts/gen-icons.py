#!/usr/bin/env python3
"""Generate src/icons.rs from the lucide package the frontend already uses.

The prototype used to ship 64x64 PNGs of the sidebar glyphs, which the software
renderer scaled down and colourised. That looked soft and sat off the text
baseline. Slint draws SVG path commands directly, so we take the same geometry
the shipping app gets from @lucide/svelte (24x24 viewbox, 2px round stroke) and
emit it as Rust string constants.

Usage: python3 scripts/gen-icons.py [path/to/@lucide/svelte/icons]
Default path is frontend/node_modules/@lucide/svelte/dist/icons, relative to the
repo root. Regenerate after bumping the lucide version in frontend/package.json.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

# Prototype icon name -> lucide icon file name.
ICONS = {
    "home": "house",
    "wifi": "wifi",
    "bluetooth": "bluetooth",
    "share": "share-2",
    "monitor": "monitor",
    "volume": "volume-2",
    "battery": "battery-full",
    "mouse": "mouse",
    "keyboard": "keyboard",
    "printer": "printer",
    "palette": "palette",
    "window": "app-window",
    "lock": "lock",
    "bell": "bell",
    "grid": "layout-grid",
    "package": "package",
    "power": "power",
    "download": "download",
    "history": "history",
    "drive": "hard-drive",
    "memory": "memory-stick",
    "shield": "shield",
    "users": "users",
    "globe": "globe",
    "a11y": "accessibility",
    "info": "info",
    "search": "search",
    "moon": "moon",
    "zap": "zap",
    "plane": "plane",
}

NODE_RE = re.compile(r"const iconNode = (\[.*?\]);", re.S)


def num(value) -> str:
    """Format SVG numbers without a trailing .0."""
    f = float(value)
    return str(int(f)) if f == f.is_integer() else repr(f)


def attrs(node: dict) -> dict:
    return node[1]


def node_to_path(tag: str, a: dict) -> str:
    if tag == "path":
        d = a["d"].strip()
        # Lucide marks a dot with a zero-length segment ("M12 20h.01"). Some
        # strokers, Slint's included, skip the round cap for a zero-length
        # subpath, so give the segment a tiny length and let the cap draw it.
        return re.sub(r"([hv])\s*\.01\b", r"\g<1>0.1", d)
    if tag == "line":
        return f"M {num(a['x1'])} {num(a['y1'])} L {num(a['x2'])} {num(a['y2'])}"
    if tag in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        pieces = [f"M {pts[0]} {pts[1]}"]
        for i in range(2, len(pts), 2):
            pieces.append(f"L {pts[i]} {pts[i + 1]}")
        if tag == "polygon":
            pieces.append("Z")
        return " ".join(pieces)
    if tag in ("circle", "ellipse"):
        cx, cy = float(a["cx"]), float(a["cy"])
        rx = float(a.get("rx", a.get("r")))
        ry = float(a.get("ry", a.get("r", rx)))
        return (
            f"M {num(cx - rx)} {num(cy)} "
            f"A {num(rx)} {num(ry)} 0 1 1 {num(cx + rx)} {num(cy)} "
            f"A {num(rx)} {num(ry)} 0 1 1 {num(cx - rx)} {num(cy)} Z"
        )
    if tag == "rect":
        x, y = float(a["x"]), float(a["y"])
        w, h = float(a["width"]), float(a["height"])
        rx = float(a.get("rx", 0))
        ry = float(a.get("ry", rx))
        if rx <= 0 or ry <= 0:
            return f"M {num(x)} {num(y)} H {num(x + w)} V {num(y + h)} H {num(x)} Z"
        return (
            f"M {num(x + rx)} {num(y)} "
            f"H {num(x + w - rx)} "
            f"A {num(rx)} {num(ry)} 0 0 1 {num(x + w)} {num(y + ry)} "
            f"V {num(y + h - ry)} "
            f"A {num(rx)} {num(ry)} 0 0 1 {num(x + w - rx)} {num(y + h)} "
            f"H {num(x + rx)} "
            f"A {num(rx)} {num(ry)} 0 0 1 {num(x)} {num(y + h - ry)} "
            f"V {num(y + ry)} "
            f"A {num(rx)} {num(ry)} 0 0 1 {num(x + rx)} {num(y)} Z"
        )
    raise SystemExit(f"unsupported SVG node <{tag}>")


def icon_commands(path: Path) -> str:
    text = path.read_text()
    match = NODE_RE.search(text)
    if not match:
        raise SystemExit(f"no iconNode in {path}")
    nodes = json.loads(match.group(1))
    return " ".join(node_to_path(tag, a) for tag, a in nodes).replace('"', '\\"')


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    icons_dir = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else root.parent
        / "frontend"
        / "node_modules"
        / "@lucide"
        / "svelte"
        / "dist"
        / "icons"
    )
    if not icons_dir.is_dir():
        raise SystemExit(
            f"lucide icons not found at {icons_dir}; pass the icons directory"
        )

    lines = [
        "//! Icon geometry for the Slint prototype.",
        "//!",
        "//! Generated by scripts/gen-icons.py from @lucide/svelte, the icon set the",
        "//! shipping app uses. Each constant is SVG path data in a 24x24 viewbox,",
        "//! meant for a Path element with a 2px round stroke (see VectorIcon in",
        "//! theme.slint). Do not edit by hand.",
        "",
        "pub fn commands(name: &str) -> &'static str {",
        "    match name {",
    ]
    body = []
    for short, lucide in ICONS.items():
        cmds = icon_commands(icons_dir / f"{lucide}.svelte")
        const = short.upper()
        lines.append(f'        "{short}" => {const},')
        body.append(f'pub const {const}: &str = "{cmds}";')
    lines += ['        _ => "",', "    }", "}", ""]
    lines += ["\n".join(body), ""]

    out = root / "src" / "icons.rs"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(ICONS)} icons)")


if __name__ == "__main__":
    main()
